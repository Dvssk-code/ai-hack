// Приветствие на странице команды
function greeting(task){
  return "Команда " + task.id + " — на связи ВЕГА, ваш инженер на хакатоне.\n" +
    "Задание: «" + task.title + "».\n" +
    "Опишите, что за приложение и что должно быть на экране — соберу код. По ходу сверяйтесь с требованиями и пишите, чего не хватает — доработаю. Таймер тикает.";
}

// Попытка 1-3: запрос к нейронке (Yandex API), если ключ настроен;
// иначе — ответ из базовой сценарной базы (код рабочий в любом случае)
async function studentReply(task, history){
  if (aiReady()) {
    try {
      const raw = await aiAsk(task, history);
      const ans = parseAnswer(raw);
      if (ans && ans.code) return ans;
    } catch (e) { /* переходим на сценарный ответ */ }
  }
  return scriptReply(task, history);
}

// Сценарная база: первый запрос — базовая версия, дальше — полная версия
function scriptReply(task, history){
  const n = history.length / 2;
  if (n === 0) return { text: task.v1.text, code: task.v1 };
  if (n === 1) return { text: "Принято. Доработала до полной версии по всем требованиям — код ниже.", code: task.final };
  return { text: "Полная версия ниже ещё раз — вставляйте и проверяйте по списку требований.", code: task.final };
}

// Попытка 4: финал, код из задания, дальше лимит исчерпан
function finalAnswer(task){
  return {
    text: "Лимит запросов исчерпан.\n" +
          "Код ниже — полная версия: вставляйте в редактор, запускайте, проверяйте по требованиям и сдавайте. Дальше вопросов не принимаю.",
    code: task.final
  };
}

